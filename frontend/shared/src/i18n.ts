const dictionaries: Record<LanguageCode, Record<TranslationKey, string>> = {
  'zh-CN': zhCN,
  'en-US': enUS
};

export type I18nKey = TranslationKey;

export function isLanguageCode(value: string): value is LanguageCode {
  return languages.some((language) => language.code === value);
}

export function getText(language: string, key: I18nKey): string {
  const selected = isLanguageCode(language) ? language : DEFAULT_LANGUAGE;
  return dictionaries[selected][key] ?? dictionaries[DEFAULT_LANGUAGE][key];
}

export function createTranslator(language: string) {
  return (key: I18nKey) => getText(language, key);
}
